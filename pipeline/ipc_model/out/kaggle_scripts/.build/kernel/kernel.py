"""Kaggle script kernel: set up the repo layout from the two private datasets and run one command.
Generated by scripts/kaggle/push_code.sh (the CONFIG line is filled in at push time)."""
import json, os, shutil, subprocess, sys, tarfile, time
from pathlib import Path

CONFIG = json.loads('{"cmd": "python pipeline/ipc_model/ipc_data_v2.py --label w20 --out pipeline/out/ipc_model_v2_w20 && python pipeline/ipc_model/train_ipc_v2.py --out pipeline/out/ipc_model_v2_w20 --cv-only --no-ablation", "pip": [], "data": "/kaggle/input/drought-signals", "code": "/kaggle/input/drought-code", "pushed_at": "2026-10-16T20:32:37+00:00"}')
WORK = Path("/kaggle/working"); OUT = WORK / "out"; PIPE = WORK / "pipeline"
OUT.mkdir(parents=True, exist_ok=True)
t0 = time.time()
print("== config", json.dumps(CONFIG), flush=True)

def find_input(slug: str) -> str:
    """Kaggle mounts datasets at /kaggle/input/<slug> (old) or /kaggle/input/datasets/<owner>/<slug> (new)."""
    for c in [Path("/kaggle/input") / slug, *Path("/kaggle/input/datasets").glob(f"*/{slug}"),
              *Path("/kaggle/input").glob(f"**/{slug}")]:
        if c.is_dir():
            return str(c)
    sys.exit(f"!! dataset {slug} not mounted under /kaggle/input: "
             f"{sorted(str(p) for p in Path('/kaggle/input').glob('**/*') if p.is_dir())}")
for k in ("code", "data"):
    CONFIG[k] = find_input(Path(CONFIG[k]).name)
print("== inputs:", CONFIG["code"], CONFIG["data"], flush=True)

# --- code: copy dataset -> /kaggle/working/pipeline (untar any dir that arrived as a tar)
if PIPE.exists():
    shutil.rmtree(PIPE)
shutil.copytree(CONFIG["code"], PIPE)
for t in list(PIPE.rglob("*.tar")) + list(PIPE.rglob("*.tar.gz")):
    with tarfile.open(t) as tf:
        tf.extractall(t.parent)
    t.unlink()
(PIPE / "data").mkdir(exist_ok=True)
(PIPE / "cache").mkdir(exist_ok=True)
# pipeline/out -> /kaggle/working/out so every script's default OUT_DIR lands in the kernel output
if (PIPE / "out").exists():
    shutil.rmtree(PIPE / "out")
os.symlink(OUT, PIPE / "out")

# --- data: link the read-only dataset files into pipeline/data (timesfm_* belong in out/)
data = Path(CONFIG["data"])
n = 0
for f in sorted(data.iterdir()):
    if f.name == "dataset-metadata.json":
        continue
    if f.name.startswith("timesfm_"):
        shutil.copy2(f, OUT / f.name)
    else:
        os.symlink(f, PIPE / "data" / f.name)
    n += 1
print(f"== linked {n} data files; code files: {sum(1 for _ in PIPE.rglob('*.py'))}", flush=True)

# --- deps
def have(mod):
    try:
        __import__(mod); return True
    except Exception:
        return False
pip = list(CONFIG["pip"])
if not have("lightgbm"):
    pip.append("lightgbm")
if pip:
    print("== pip install", pip, flush=True)
    subprocess.run([sys.executable, "-m", "pip", "install", "-q", *pip], check=False)
import importlib
for m in ["numpy", "pandas", "sklearn", "lightgbm", "torch"]:
    try:
        print(f"   {m} {importlib.import_module(m).__version__}")
    except Exception:
        print(f"   {m} (not installed)")
subprocess.run("nvidia-smi -L 2>/dev/null || echo '   no GPU'", shell=True)

# --- run
print(f"== run: {CONFIG['cmd']}", flush=True)
env = dict(os.environ, PY=sys.executable, PYTHONUNBUFFERED="1")
rc = subprocess.call(CONFIG["cmd"], shell=True, cwd=WORK, env=env)
dt = time.time() - t0
(OUT / "kaggle_run.json").write_text(json.dumps({**CONFIG, "exit_code": rc, "seconds": round(dt, 1),
                                                 "pipeline_files": sorted(p.name for p in OUT.iterdir())}, indent=1))
print(f"== done rc={rc} in {dt/60:.1f} min; outputs:", flush=True)
for p in sorted(OUT.iterdir()):
    print(f"   {p.stat().st_size:>12,d}  {p.name}")
# the symlink must not stay in /kaggle/working (output walker) -> drop the pipeline copy entirely
os.unlink(PIPE / "out"); shutil.rmtree(PIPE, ignore_errors=True)
if rc != 0:
    sys.exit(rc)
