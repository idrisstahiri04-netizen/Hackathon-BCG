"""Write js/config.local.js (gitignored) so the globe / live UI can call operator endpoints.

    python backend/make_ui_config.py [--api http://localhost:8000]

The file sets window.SMS_API_KEY (= ADMIN_TOKEN from /home/looooo/bcg/.env) and
window.SMS_API_BASE. js/live.js sends it as header X-API-Key. Never commit the file.
"""
from __future__ import annotations

import argparse
import json
import os
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from backend import db  # noqa: E402  (loads .env)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--api", default="http://localhost:8000")
    a = ap.parse_args()
    db.ensure_admin_token()
    out = db.REPO_DIR / "js" / "config.local.js"
    out.write_text("// LOCAL ONLY - generated by backend/make_ui_config.py, gitignored. Do not commit.\n"
                   f"window.SMS_API_BASE = {json.dumps(a.api)};\n"
                   f"window.SMS_API_KEY = {json.dumps(os.environ['ADMIN_TOKEN'])};\n")
    os.chmod(out, 0o600)
    print(f"wrote {out} (token not shown)")


if __name__ == "__main__":
    main()
