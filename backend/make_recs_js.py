"""Write data/recommendations.js (window.RECS) from backend/recommendations.yaml for the replay UI."""
import json
from pathlib import Path

import yaml

root = Path(__file__).resolve().parent
lib = yaml.safe_load((root / "recommendations.yaml").read_text(encoding="utf-8"))
out = root.parent / "data" / "recommendations.js"
out.write_text("// generated by backend/make_recs_js.py - demo content, to be validated with NDMA / WHH\n"
               "window.RECS = " + json.dumps(lib, ensure_ascii=False) + ";\n", encoding="utf-8")
print("wrote", out)
